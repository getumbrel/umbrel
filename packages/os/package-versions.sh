#!/bin/bash
# Prints the software installed in an umbrelOS image and its version. CI runs
# it inside each image and compares the output against
# packages/os/package-versions/.

set -euo pipefail

export LC_ALL=C

cat <<'EOF'
# Software installed in the umbrelOS image, and its version.
#
# CI regenerates this list from the image it builds for every PR and fails if
# it doesn't match this file, so any change to what's installed, or to which
# version, shows up in review instead of shipping unnoticed.
#
# If the check fails on your PR, read the diff:
#
# - If a change is a mistake, such as a package that disappeared or a version
#   that moved when it shouldn't have, fix the build.
# - If every change is intended, update this file to match. The failing CI job
#   shows the diff. To regenerate it, run packages/os/package-versions.sh
#   inside the image, as the CI job does.
#
# Generated by packages/os/package-versions.sh.
EOF

echo
echo "## Debian packages"
echo
dpkg-query --show --showformat='${db:Status-Abbrev} ${Package} ${Version}\n' |
    awk '$1 == "ii" { print $2, $3 }' |
    sort

echo
echo "## Homebrew packages"
echo
for version in /opt/linuxbrew/Cellar/*/*; do
    echo "$(basename "$(dirname "${version}")") $(basename "${version}")"
done | sort

echo
echo "## Bundled container images"
echo
for image in /images/*; do
    echo "$(basename "${image}") $(tar --extract --to-stdout --file "${image}" manifest.json | jq --raw-output '.[0].Config' | grep --only-matching --extended-regexp '[0-9a-f]{64}')"
done | sort

echo
echo "## Other software"
echo
{
    echo "kopia $(kopia --version | awk '{ print $1 }')"
    echo "node $(node --version | sed 's/^v//')"
    echo "rclone $(rclone version | awk 'NR == 1 { sub(/^v/, "", $2); print $2 }')"
    echo "yq $(yq --version | awk '{ sub(/^v/, "", $NF); print $NF }')"
    # Node.js's bundled global packages, such as npm. umbreld is linked here
    # with `npm link`, so skip symlinks.
    for package in /usr/local/lib/node_modules/* /usr/local/lib/node_modules/@*/*; do
        [ -d "${package}" ] && [ ! -L "${package}" ] && [ -f "${package}/package.json" ] || continue
        node --print 'const {name, version} = require(process.argv[1]); `${name} ${version}`' "${package}/package.json"
    done
} | sort

# Anything installed outside apt also needs a version line above. List every
# executable that no Debian package owns, so a newly added one shows up in the
# diff even if nobody added it to the sections above. Homebrew, umbreld, and
# Node.js's global packages are covered elsewhere. Kernel modules that DKMS
# builds and the boot files that kernel and firmware packages copy into /boot
# come from Debian packages that are already listed.
echo
echo "## Executables not installed by a Debian package"
echo
python3 - <<'EOF'
import glob
import os

owned = set()
for listing in glob.glob("/var/lib/dpkg/info/*.list"):
    with open(listing) as file:
        for path in file:
            path = path.rstrip("\n")
            # Debian packages can list files under the merged-/usr symlinks.
            for prefix in ("/bin/", "/sbin/", "/lib/", "/lib64/"):
                if path.startswith(prefix):
                    path = "/usr" + path
            owned.add(path)

skip = (
    "/boot",
    "/dev",
    "/images",
    "/opt/linuxbrew",
    "/opt/umbreld",
    "/proc",
    "/sys",
    "/tmp",
    "/usr/lib/modules",
    "/usr/local/lib/node_modules",
)

for root, directories, files in os.walk("/"):
    directories[:] = sorted(d for d in directories if os.path.join(root, d) not in skip)
    for name in sorted(files):
        path = os.path.join(root, name)
        if path in owned or os.path.islink(path) or not os.access(path, os.X_OK):
            continue
        try:
            with open(path, "rb") as file:
                if file.read(4) != b"\x7fELF":
                    continue
        except OSError:
            continue
        print(path)
EOF
